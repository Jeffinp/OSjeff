//! X.509 chain validation for the browser's TLS 1.3 client.
//!
//! What is *not* hand-written here: path building, validity dates, host name
//! matching, `basicConstraints` / `keyUsage` / extended key usage, name
//! constraints and path-length checks all come from the reviewed
//! `rustls-webpki` crate, and the signature maths from the pure-Rust RustCrypto
//! crates (`p256`, `p384`, `rsa`, `sha2`). This module supplies:
//!
//! * the signature algorithm table webpki asks for (RSA PKCS#1 v1.5 and PSS
//!   with SHA-256/384/512, ECDSA P-256 and P-384 with SHA-256/384; RSA keys must
//!   be 2048-8192 bits);
//! * the embedded **trust store** ([`TrustStore`], data in
//!   `osjeff_core/data/trust-store.bin`, regenerated by
//!   `tools/gen-trust-store.sh`, every root listed with its SHA-256 in
//!   `trust-store.sha256`);
//! * hard limits (chain length, certificate size) and an error type
//!   ([`CertError`]) that says in plain words why a chain was refused;
//! * the TLS 1.3 `CertificateVerify` check ([`verify_handshake_signature`]).
//!
//! There is no revocation checking (no CRL, no OCSP, no stapling) and no
//! pinning; see `docs/SECURITY-MODEL.md`.

use crate::x509;
use alloc::vec::Vec;
use core::time::Duration;
use p256::ecdsa::signature::hazmat::PrehashVerifier;
use rsa::pkcs1::DecodeRsaPublicKey;
use rsa::traits::PublicKeyParts;
use rustls_pki_types::{
    AlgorithmIdentifier, CertificateDer, InvalidSignature, ServerName,
    SignatureVerificationAlgorithm, UnixTime, alg_id,
};
use sha2::{Digest, Sha256, Sha384, Sha512};

/// Longest handshake the verifier tolerates in total, for the caller's
/// deadline (the TLS layer enforces it; kept here so the policy is in one
/// place and documented).
pub const MAX_HANDSHAKE_MS: u64 = 30_000;
/// Smallest and largest RSA modulus accepted (bits).
pub const RSA_MIN_BITS: usize = 2048;
pub const RSA_MAX_BITS: usize = 8192;

// ---- errors ----

/// Why a server certificate chain was refused.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum CertError {
    /// A certificate could not be parsed.
    BadEncoding,
    /// A certificate or the whole chain exceeds the size limits.
    TooLarge,
    /// More certificates than [`x509::MAX_CHAIN_LEN`], or a path too deep.
    ChainTooLong,
    /// `notAfter` is in the past.
    Expired,
    /// `notBefore` is in the future.
    NotYetValid,
    /// The certificate is not valid for the host name asked for.
    NameMismatch,
    /// The server's own certificate signed itself.
    SelfSigned,
    /// No path to a trusted root (unknown root or missing intermediate).
    UnknownIssuer,
    /// A signature does not verify.
    BadSignature,
    /// A certificate is used as a CA without being one (or the reverse).
    NotCa,
    /// Name constraints, path-length or key-usage constraints violated.
    Constraint,
    /// Signature algorithm or key size not supported.
    Unsupported,
    /// The system clock is not a plausible date, so validity cannot be judged.
    ClockUnset,
    /// Anything else webpki reports.
    Other,
}

impl CertError {
    /// Short reason for the serial log (English, ASCII). The person sees `web.err.cert.*`.
    pub fn reason(self) -> &'static str {
        match self {
            CertError::BadEncoding => "malformed certificate",
            CertError::TooLarge => "certificate too large",
            CertError::ChainTooLong => "chain too long",
            CertError::Expired => "expired",
            CertError::NotYetValid => "not yet valid",
            CertError::NameMismatch => "name mismatch",
            CertError::SelfSigned => "self-signed, untrusted chain",
            CertError::UnknownIssuer => "untrusted chain",
            CertError::BadSignature => "bad signature",
            CertError::NotCa => "invalid CA in chain",
            CertError::Constraint => "chain constraint violated",
            CertError::Unsupported => "unsupported algorithm",
            CertError::ClockUnset => "system clock wrong",
            CertError::Other => "chain rejected",
        }
    }

    /// True when a wrong system clock is a plausible cause: the UI adds the
    /// "hora do sistema incorreta / nao confirmada" hint.
    pub fn clock_may_be_to_blame(self) -> bool {
        matches!(
            self,
            CertError::Expired | CertError::NotYetValid | CertError::ClockUnset
        )
    }
}

// ---- signature algorithms ----

#[derive(Clone, Copy, Debug)]
enum Hash {
    S256,
    S384,
    S512,
}

impl Hash {
    fn digest(self, msg: &[u8]) -> Vec<u8> {
        match self {
            Hash::S256 => Sha256::digest(msg).to_vec(),
            Hash::S384 => Sha384::digest(msg).to_vec(),
            Hash::S512 => Sha512::digest(msg).to_vec(),
        }
    }
}

#[derive(Debug)]
struct Ecdsa {
    p384: bool,
    hash: Hash,
    pk_alg: AlgorithmIdentifier,
    sig_alg: AlgorithmIdentifier,
}

impl SignatureVerificationAlgorithm for Ecdsa {
    fn verify_signature(
        &self,
        public_key: &[u8],
        message: &[u8],
        signature: &[u8],
    ) -> Result<(), InvalidSignature> {
        let digest = self.hash.digest(message);
        if self.p384 {
            let key = p384::ecdsa::VerifyingKey::from_sec1_bytes(public_key)
                .map_err(|_| InvalidSignature)?;
            let sig = p384::ecdsa::Signature::from_der(signature).map_err(|_| InvalidSignature)?;
            key.verify_prehash(&digest, &sig)
                .map_err(|_| InvalidSignature)
        } else {
            let key = p256::ecdsa::VerifyingKey::from_sec1_bytes(public_key)
                .map_err(|_| InvalidSignature)?;
            let sig = p256::ecdsa::Signature::from_der(signature).map_err(|_| InvalidSignature)?;
            key.verify_prehash(&digest, &sig)
                .map_err(|_| InvalidSignature)
        }
    }
    fn public_key_alg_id(&self) -> AlgorithmIdentifier {
        self.pk_alg
    }
    fn signature_alg_id(&self) -> AlgorithmIdentifier {
        self.sig_alg
    }
}

#[derive(Debug)]
struct RsaAlg {
    pss: bool,
    hash: Hash,
    sig_alg: AlgorithmIdentifier,
}

fn rsa_key(public_key: &[u8]) -> Result<rsa::RsaPublicKey, InvalidSignature> {
    let key = rsa::RsaPublicKey::from_pkcs1_der(public_key).map_err(|_| InvalidSignature)?;
    let bits = key.size() * 8;
    if !(RSA_MIN_BITS..=RSA_MAX_BITS).contains(&bits) {
        return Err(InvalidSignature);
    }
    Ok(key)
}

impl SignatureVerificationAlgorithm for RsaAlg {
    fn verify_signature(
        &self,
        public_key: &[u8],
        message: &[u8],
        signature: &[u8],
    ) -> Result<(), InvalidSignature> {
        use rsa::signature::Verifier;
        let key = rsa_key(public_key)?;
        // The signature must be exactly the modulus length.
        if signature.len() != key.size() {
            return Err(InvalidSignature);
        }
        macro_rules! check {
            ($h:ty) => {{
                if self.pss {
                    let sig =
                        rsa::pss::Signature::try_from(signature).map_err(|_| InvalidSignature)?;
                    rsa::pss::VerifyingKey::<$h>::new(key)
                        .verify(message, &sig)
                        .map_err(|_| InvalidSignature)
                } else {
                    let sig = rsa::pkcs1v15::Signature::try_from(signature)
                        .map_err(|_| InvalidSignature)?;
                    rsa::pkcs1v15::VerifyingKey::<$h>::new(key)
                        .verify(message, &sig)
                        .map_err(|_| InvalidSignature)
                }
            }};
        }
        match self.hash {
            Hash::S256 => check!(Sha256),
            Hash::S384 => check!(Sha384),
            Hash::S512 => check!(Sha512),
        }
    }
    fn public_key_alg_id(&self) -> AlgorithmIdentifier {
        alg_id::RSA_ENCRYPTION
    }
    fn signature_alg_id(&self) -> AlgorithmIdentifier {
        self.sig_alg
    }
}

